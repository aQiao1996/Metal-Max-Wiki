/** 使用固定参考译名，未知孔位保留来源原文。 */
export function formatVehicleMount(raw: string): string {
  return Object.hasOwn(mounts, raw) ? mounts[raw] : raw
}

/** 标记已收录的固定武装名称。 */
export function isFixedVehicleMount(raw: string): boolean {
  return (
    Object.hasOwn(mounts, raw) &&
    !['大砲タイプ', '機銃タイプ', 'S-Eタイプ', 'なし', '選択'].includes(raw)
  )
}
